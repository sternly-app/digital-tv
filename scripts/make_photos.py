"""Write photos/photos.js from the images in photos/. Run after adding or removing photos.

Usage:
  python3 scripts/make_photos.py           list the photos (order: file name)
  python3 scripts/make_photos.py --shrink  also resize to 1200px and fix phone rotation, in place (needs: pip3 install pillow)

Older LG TVs (webOS 6) ignore the rotation stored in phone photos, so --shrink is worth running once.
"""
import json, pathlib, sys

root = pathlib.Path(__file__).resolve().parent.parent
folder = root / "photos"
EXT = {".jpg", ".jpeg", ".png", ".webp"}
MAX = 1200

folder.mkdir(exist_ok=True)
files = sorted((p for p in folder.iterdir() if p.is_file() and p.suffix.lower() in EXT), key=lambda p: p.name.lower())

if "--shrink" in sys.argv:
    try:
        from PIL import Image, ImageOps
    except ImportError:
        sys.exit("Pillow is not installed. Run: pip3 install pillow")
    for p in files:
        with Image.open(p) as im:
            fixed = ImageOps.exif_transpose(im)
            if max(fixed.size) <= MAX and fixed is im:
                continue
            fixed.thumbnail((MAX, MAX))
            if p.suffix.lower() in (".jpg", ".jpeg"):
                fixed.convert("RGB").save(p, "JPEG", quality=82, optimize=True)
            else:
                fixed.save(p)
            print("shrunk", p.name, fixed.size)

names = [p.name for p in files]
(folder / "photos.js").write_text(
    "/* Generated by scripts/make_photos.py. Lists the photos in this folder for the slideshow. */\n"
    "window.PHOTOS = " + json.dumps(names, indent=1) + ";\n",
    encoding="utf-8",
)
print(len(names), "photos listed in photos/photos.js")
for p in files:
    kb = p.stat().st_size // 1024
    if kb > 600:
        print("  large:", p.name, kb, "KB (run with --shrink)")
